"""Convert the HUD's BDF fonts into firmware/panel/fonts.py.

Usage (from the repo root):
    .venv\\Scripts\\python tools\\build_fonts.py [BDF_DIR]

BDF_DIR defaults to the oled-bonnet project's fonts/ folder. Output is one
module with two fonts in the same shape as panel/font5x7.py: column bytes
per glyph over ASCII 32..126, bit 0 = top row of the cell. Re-run it only if
the fonts change; the generated file is committed.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "panel", "fonts.py")
DEFAULT_DIR = r"D:\code\boards\oled\oled-bonnet\fonts"
FIRST, LAST = 32, 126

FONTS = (
    # (python name, bdf file, header note)
    ("SPLEEN", "spleen-5x8.bdf",
     "Spleen 5x8 1.9.1, Copyright (c) 2018-2026 Frederic Cambus.\n"
     "# SPDX-License-Identifier: BSD-2-Clause (full text: panel/LICENSE.spleen)"),
    ("SMALL", "4x6.bdf",
     "X11 misc-fixed 4x6: \"Public domain font.  Share and enjoy.\""),
)


def parse(path):
    """-> (cell_w, cell_h, {code: [column bytes]})"""
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    ascent = cell_w = cell_h = None
    glyphs = {}
    i = 0
    while i < len(lines):
        p = lines[i].split()
        if not p:
            i += 1
            continue
        if p[0] == "FONTBOUNDINGBOX":
            cell_w, cell_h = int(p[1]), int(p[2])
        elif p[0] == "FONT_ASCENT":
            ascent = int(p[1])
        elif p[0] == "STARTCHAR":
            enc = bbx = None
            rows = []
            i += 1
            while lines[i] != "ENDCHAR":
                q = lines[i].split()
                if q[0] == "ENCODING":
                    enc = int(q[1])
                elif q[0] == "BBX":
                    bbx = tuple(map(int, q[1:5]))
                elif q[0] == "BITMAP":
                    i += 1
                    while lines[i] != "ENDCHAR":
                        rows.append(int(lines[i], 16))
                        i += 1
                    break
                i += 1
            if enc is not None and FIRST <= enc <= LAST:
                bw, bh, bx, by = bbx
                nbits = ((bw + 7) // 8) * 8
                cols = [0] * cell_w
                for r, v in enumerate(rows):
                    y = ascent - by - bh + r  # row within the cell, 0 = top
                    for cx in range(bw):
                        if v & (1 << (nbits - 1 - cx)):
                            x = bx + cx
                            if 0 <= x < cell_w and 0 <= y < cell_h:
                                cols[x] |= 1 << y
                glyphs[enc] = cols
        i += 1
    return cell_w, cell_h, glyphs


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DIR
    out = [
        "# Generated by tools/build_fonts.py from the oled-bonnet BDFs. Don't edit.",
        "# Same shape as panel/font5x7.py: W column bytes per glyph, bit 0 = top",
        "# row of the cell, ASCII 0x20..0x7E. ADV is the advance per character",
        "# (the gap is built into the cell).",
        "",
    ]
    for name, fname, note in FONTS:
        w, h, glyphs = parse(os.path.join(src, fname))
        data = []
        for c in range(FIRST, LAST + 1):
            data.extend(glyphs.get(c, glyphs[ord("?")]))
        out += [
            "# " + note,
            "class %s:" % name,
            "    FIRST = 0x%02X" % FIRST,
            "    LAST = 0x%02X" % LAST,
            "    W = %d" % w,
            "    H = %d" % h,
            "    ADV = %d" % w,
            "    GLYPHS = bytes((",
        ]
        for c in range(FIRST, LAST + 1):
            o = (c - FIRST) * w
            out.append("        %s  # %r" % (
                " ".join("0x%02X," % b for b in data[o:o + w]), chr(c)))
        out += ["    ))", "", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
